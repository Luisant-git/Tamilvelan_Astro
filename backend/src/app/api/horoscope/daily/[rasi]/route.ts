function dayIndexFromDateStr(dateStr: string): number {
  return Math.floor(Date.parse(`${dateStr}T00:00:00Z`) / 86400000);
}

// Rotates a fixed 12-wide window of the pool by the day index. Consecutive
// rasis (offset 0..11) always land on distinct indices within one day
// (guarantees requirement: no two rasis share a prediction on the same
// date), and advancing the date by one always shifts every rasi's index by
// exactly 1 (guarantees requirement: never the same as yesterday).
function pickForRasi(pool: string[], rasi: number, dateStr: string): string {
  const day = dayIndexFromDateStr(dateStr);
  const idx = ((day + (rasi - 1)) % pool.length + pool.length) % pool.length;
  return pool[idx];
}

export async function GET(_req: Request, { params }: { params: { rasi: string } }) {
  const rasi = parseInt(params.rasi, 10);
  if (Number.isNaN(rasi) || rasi < 1 || rasi > 12) {
    return NextResponse.json({ error: 'சரியான ராசி எண் தேவை (1-12)' }, { status: 400 });
  }
  const today = new Date().toISOString().split('T')[0];
  return NextResponse.json({
    rasi,
    rasiName: RASI_NAMES_TAMIL[rasi - 1],
    date: today,
    prediction: pickForRasi(DETAILED_PREDICTIONS, rasi, today),
    preview: pickForRasi(SHORT_PREVIEWS, rasi, today),
  });
}
